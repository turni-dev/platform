/**
 * Единая ловушка для спам-ботов: скрытое от людей CSS-полем поле, которое
 * ни один настоящий посетитель не заполнит. Любая форма, использующая этот
 * слой, вызывает эту же проверку под своим именем поля — реализация ловушки
 * не копипастится в каждую форму заново.
 *
 * Вызывающая сторона обязана ответить как при успехе, если ловушка
 * сработала (не подсказывать боту, что его распознали) — это решение
 * принимает форма, а не этот модуль.
 */
export function isHoneypotTripped(form: FormData, fieldName: string): boolean {
  const value = form.get(fieldName);

  return typeof value === 'string' && value.trim().length > 0;
}
